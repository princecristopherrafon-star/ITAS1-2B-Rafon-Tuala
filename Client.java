private void connect() {
    try {
        socket = new Socket(txtIP.getText().trim(), Integer.parseInt(txtPORT.getText().trim()));
        out = new PrintWriter(socket.getOutputStream(), true);
        in = new BufferedReader(new InputStreamReader(socket.getInputStream()));
        out.println(txtNICK.getText());
        connected = true;
        DefaultListModel<String> um = (DefaultListModel<String>) listUsers1.getModel();
um.clear();
um.addElement(txtNICK.getText());
        txtChat.append("Connected as " + txtNICK.getText() + "\n");
        btnConnect.setEnabled(false);
        btnDisconnect.setEnabled(true);
        new Thread(() -> {
            try {
                String m;
                while ((m = in.readLine()) != null) {
                    String msg = m;
                   SwingUtilities.invokeLater(() -> {
    if (msg.startsWith("USERS:")) {
        String[] names = msg.substring(6).split(",");
        DefaultListModel<String> m2 = (DefaultListModel<String>) listUsers1.getModel();
        m2.clear();
        for (String n : names) {
            if (!n.trim().isEmpty()) m2.addElement(n.trim());
        }
        return;
    }
    txtChat.append(msg + "\n");
});


                }
            } catch (Exception e) {}
        }).start();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Cannot connect: " + e.getMessage());
    }
}

private void disconnect() {
    try { connected = false; if (socket != null) socket.close(); } catch (Exception e) {}
    btnConnect.setEnabled(true);
    btnDisconnect.setEnabled(false);
}

private void sendChat() {
    String msg = txtMsg.getText().trim();
    if (msg.isEmpty()) return;
    if (connected && out != null) out.println(msg);
    txtChat.append("Me: " + msg + "\n");
    txtMsg.setText("");
}

private void createOrder() {
    currentOrder.clear(); totalBill = 0;
    txtOrders.setText("NEW ORDER for " + txtNICK.getText() + "\n---\n");
}

private void addItem() {
    String item = txtItem.getText().trim();
    if (item.isEmpty() || txtQty.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter Item and Qty"); return;
    }
    int qty = Integer.parseInt(txtQty.getText().trim());
    double price = 50;
    if (item.equalsIgnoreCase("Rice")) price = 20;
    if (item.equalsIgnoreCase("Chicken")) price = 80;
    if (item.equalsIgnoreCase("Burger")) price = 60;
    if (item.equalsIgnoreCase("Soda")) price = 30;
    double lineTotal = price * qty;
    totalBill += lineTotal;
    currentOrder.add(item + " x" + qty + " = P" + lineTotal);
    txtOrders.append(item + " x" + qty + " = P" + lineTotal + "\n");
    txtItem.setText(""); txtQty.setText("");
}


    

